"""Write the `inventory` part of pipeline/sources.yaml from the inventory files.

Every particular P001-P267 gets one row for its advertised url and one for each
retrieval url (where the content actually was in the research pass). The
hand-curated `demo` part of sources.yaml is read back and kept as it is.

    python3 pipeline/make_sources.py           rewrite sources.yaml
    python3 pipeline/make_sources.py --check   exit 1 if sources.yaml is out of date
"""
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SOURCES_PATH = ROOT / "pipeline" / "sources.yaml"
GRAPH_PATH = ROOT / "data" / "inventory" / "Claude-Waterloo-context.json"
CLASSIFIED_PATH = ROOT / "data" / "inventory" / "Waterloo-particulars-classified.json"

HEADER = """\
# Sources pipeline/fetch.py --all fetches.
#
# inventory: generated by pipeline/make_sources.py from data/inventory/. Don't edit it by hand;
#            change the inventory and run `python3 pipeline/make_sources.py`.
# demo:      hand-curated official sources the demo matters rely on. Every url here was copied
#            from the classification guide or the particulars file; `guide` says where.
"""


def is_web_url(url):
    return isinstance(url, str) and url.startswith(("http://", "https://"))


def inventory_rows():
    graph = json.loads(GRAPH_PATH.read_text(encoding="utf-8"))
    classified = json.loads(CLASSIFIED_PATH.read_text(encoding="utf-8"))
    family_of = {p["id"]: p["family"] for p in classified["particulars"]}

    rows = []
    for particular in graph["particulars"]:
        urls = [(particular["url"], "inventory url")]
        urls += [(url, "retrieval url") for url in particular["retrieval_urls"]]
        seen = set()
        for url, why in urls:
            if not is_web_url(url) or url in seen:
                continue
            seen.add(url)
            if why == "inventory url" and url in particular["retrieval_urls"]:
                why = "inventory url (also the retrieval url)"
            rows.append({
                "particular": particular["id"],
                "url": url,
                "why": why,
                "publisher": particular["authority"],
                "family": family_of[particular["id"]],
                "title": particular["particular"],
            })
    return rows


def read_sources(path=SOURCES_PATH):
    if not Path(path).exists():
        return {"inventory": [], "demo": []}
    data = yaml.safe_load(Path(path).read_text(encoding="utf-8")) or {}
    return {"inventory": data.get("inventory") or [], "demo": data.get("demo") or []}


def write_sources(sources, path=SOURCES_PATH):
    body = yaml.safe_dump(sources, sort_keys=False, allow_unicode=True, width=200)
    Path(path).write_text(HEADER + "\n" + body, encoding="utf-8")


def main():
    sources = read_sources()
    fresh = inventory_rows()
    if "--check" in sys.argv:
        if sources["inventory"] != fresh:
            sys.exit("pipeline/sources.yaml is out of date: run python3 pipeline/make_sources.py")
        print("pipeline/sources.yaml is up to date")
        return
    write_sources({"inventory": fresh, "demo": sources["demo"]})
    particulars = {row["particular"] for row in fresh}
    print(f"Wrote {len(fresh)} inventory rows for {len(particulars)} particulars "
          f"and kept {len(sources['demo'])} demo sources -> {SOURCES_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
